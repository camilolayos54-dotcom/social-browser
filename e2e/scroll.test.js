const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { _electron: electron } = require('playwright-core');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');

const project = path.resolve(__dirname, '..');
test('reads visible results and discovers new controls in a nested scroll area', { timeout: 45000 }, async () => {
  const entries = Array.from({ length: 35 }, (_, index) => `<article style="height:115px"><p>Oportunidad ${index}</p><time datetime="2026-11-19T10:00:00Z">Hoy</time><a href="/post/${index}">Ver publicación ${index}</a><button>Contacto ${index}</button></article>`).join('');
  const server = http.createServer((_, response) => response.end(`<title>Resultados locales</title><style>body{margin:0}main{height:400px;overflow:auto;width:100%}</style><main>${entries}</main>`));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'social-scroll-'));
  const url = `http://127.0.0.1:${server.address().port}/`;
  const args = ['--disable-gpu', `--user-data-dir=${directory}`, project];
  if (process.env.SOCIAL_BROWSER_TEST_NO_SANDBOX === '1') args.unshift('--no-sandbox');
  let app, client;
  try {
    app = await electron.launch({ executablePath: require('electron'), args });
    const page = await app.firstWindow();
    await page.locator('#url').fill(url);
    await page.locator('#address-form').dispatchEvent('submit');
    await page.waitForFunction(() => document.querySelector('.tab')?.textContent.includes('Resultados locales'));
    await page.locator('#agent-access').click();
    await page.locator('#agent-all-profiles').uncheck();
    await page.locator('#confirm-agent').click();
    await page.waitForFunction(() => document.querySelector('#agent-access').textContent.includes('Desconectar'));
    client = new Client({ name: 'social-browser-e2e', version: '1.0.0' });
    await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(project, 'mcp-server.js')], env: { ...process.env, SOCIAL_BROWSER_USER_DATA: directory }, stderr: 'pipe' }));
    const call = async name => {
      const response = await client.callTool({ name, arguments: name === 'scroll_page' ? { direction: 'down' } : {} });
      assert.equal(response.isError, false, JSON.stringify(response));
      return JSON.parse(response.content[0].text);
    };
    const waitAbort = new AbortController();
    const pendingWait = client.callTool({ name: 'wait_page', arguments: { seconds: 10 } }, undefined, { signal: waitAbort.signal });
    await new Promise(resolve => setTimeout(resolve, 100));
    waitAbort.abort();
    await assert.rejects(pendingWait);
    const initial = await call('read_page');
    const controls = await call('inspect_controls');
    assert(initial.text.includes('Oportunidad 0'));
    assert(initial.articles.some(article => article.text.includes('Oportunidad 0') && article.links.some(link => link.url.endsWith('/post/0')) && article.date === '2026-11-19T10:00:00Z'));
    assert(!initial.text.includes('Oportunidad 20'));
    assert(controls.controls.some(control => control.label === 'Contacto 0'));
    assert(!controls.controls.some(control => control.label === 'Contacto 20'));
    const scrolled = await call('scroll_page');
    assert.equal(scrolled.moved, true);
    assert.equal(scrolled.container, 'área desplazable');
    const after = await call('read_page');
    const afterControls = await call('inspect_controls');
    assert(!after.text.includes('Oportunidad 0'));
    assert(after.text.includes('Oportunidad 4'));
    assert(after.articles.some(article => article.text.includes('Oportunidad 4') && article.links.some(link => link.url.endsWith('/post/4'))));
    assert(after.links.some(link => link.url.endsWith('/post/4')));
    assert(afterControls.controls.some(control => control.label === 'Contacto 4'));
    const opportunity = { url: initial.links[0].url, summary: 'Necesita trasteo', reason: 'Solicita un servicio', date: '' };
    let saved = await client.callTool({ name: 'save_opportunity', arguments: opportunity });
    assert.equal(saved.isError, false, JSON.stringify(saved));
    saved = await client.callTool({ name: 'save_opportunity', arguments: { ...opportunity, url: opportunity.url + '#comentario', reason: 'Cliente potencial' } });
    assert.equal(saved.isError, false);
    await page.locator('#activity-button').click();
    const history = await page.locator('#activity-list').innerText();
    assert(history.includes('Guardar oportunidad'));
    assert(history.includes('Leer página'));
    assert(history.includes('Desplazar página'));
    await page.locator('#close-activity').click();
    await page.locator('#opportunities-button').click();
    assert.equal(await page.locator('#opportunities-list article').count(), 1);
    assert((await page.locator('#opportunities-list').innerText()).includes('Cliente potencial'));
    await page.locator('#close-opportunities').click();
    await page.locator('#add-profile').click();
    await page.locator('#profile-name').fill('Segunda empresa');
    await page.locator('#profile-form button[type=submit]').click();
    await page.locator('#opportunities-button').click();
    assert.equal(await page.locator('#opportunities-list article').count(), 0);
    await page.locator('#close-opportunities').click();
    const inbox = await client.callTool({ name: 'open_inbox', arguments: { network: 'WhatsApp' } });
    assert.equal(inbox.isError, false, JSON.stringify(inbox));
    assert(inbox.content[0].text.includes('https://web.whatsapp.com/'));
    assert.equal(await page.locator('#profiles option:checked').textContent(), 'Segunda empresa');
    const pinnedTabs = await page.evaluate(() => JSON.parse(localStorage.getItem('social-state')).profiles[0].tabs);
    assert.equal(pinnedTabs.at(-1).url, 'https://web.whatsapp.com/');
    const listed = await client.callTool({ name: 'list_tabs', arguments: {} });
    assert.equal(listed.isError, false);
    const agentTabs = JSON.parse(listed.content[0].text).tabs;
    assert(agentTabs.some(item => item.url === 'https://web.whatsapp.com/' && item.active));
    const selected = await client.callTool({ name: 'select_tab', arguments: { id: agentTabs[0].id } });
    assert.equal(selected.isError, false);
    const created = await client.callTool({ name: 'open_tab', arguments: { url: 'https://example.com/example' } });
    assert.equal(created.isError, false);
    const afterCreate = await client.callTool({ name: 'list_tabs', arguments: {} });
    const newTab = JSON.parse(afterCreate.content[0].text).tabs.find(item => item.url === 'https://example.com/example');
    assert(newTab);
    assert.equal((await client.callTool({ name: 'close_tab', arguments: { id: newTab.id } })).isError, false);
    assert.equal(await page.locator('#profiles option:checked').textContent(), 'Segunda empresa');
    await page.locator('#open-inbox').click();
    await page.locator('#inbox-network').selectOption('Instagram');
    await page.locator('#inbox-form button[type=submit]').click();
    const manualTabs = await page.evaluate(() => JSON.parse(localStorage.getItem('social-state')).profiles[1].tabs);
    assert(manualTabs.at(-1).url.startsWith('https://www.instagram.com/'));
    await page.locator('#profiles').selectOption('0');
    await page.locator('#opportunities-button').click();
    assert.equal(await page.locator('#opportunities-list article').count(), 1);
    await page.locator('#close-opportunities').click();
    await client.close(); client = null;
    await app.close(); app = null;
    app = await electron.launch({ executablePath: require('electron'), args });
    const reopened = await app.firstWindow();
    await reopened.locator('#opportunities-button').click();
    assert.equal(await reopened.locator('#opportunities-list article').count(), 1);
    assert((await reopened.locator('#opportunities-list').innerText()).includes('Cliente potencial'));
    await reopened.locator('#opportunities-list button', { hasText: 'Eliminar' }).click();
    await reopened.locator('#cancel-delete-opportunity').click();
    assert.equal(await reopened.locator('#opportunities-list article').count(), 1);
    await reopened.locator('#opportunities-list button', { hasText: 'Eliminar' }).click();
    await reopened.locator('#confirm-delete-opportunity').click();
    assert.equal(await reopened.locator('#opportunities-list article').count(), 0);
  } finally {
    await client?.close();
    await app?.close();
    await new Promise(resolve => server.close(resolve));
    fs.rmSync(directory, { recursive: true, force: true });
  }
});
